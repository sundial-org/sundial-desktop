type IconComponent = ComponentType<IconProps>;

type ProviderIconCandidate = {
  backendProvider?: string | null;
  provider?: string | null;
  id?: string | null;
};

export function getProviderIcon(option: ProviderIconCandidate): IconComponent | null {
  const id = (option.id ?? '').toLowerCase();
  const provider = (option.provider ?? '').toLowerCase();
  const backendProvider = (option.backendProvider ?? '').toLowerCase();

  if (backendProvider === 'claude' || provider === 'anthropic' || id.includes('claude')) {
    return ClaudeIcon;
  }
  if (provider === 'openai' || id.includes('/openai/') || id.startsWith('openai/') || id.includes('gpt-')) {
    return OpenAIIcon;
  }
  if (provider === 'google' || id.includes('gemini') || id.includes('/google/')) {
    return GeminiIcon;
  }
  if (id.includes('kimi') || id.includes('moonshotai')) {
    return KimiIcon;
  }
  return null;
}

/** Brand color per icon (product colors, matching lib/workspace/agent-brand.ts
 *  where the same brand exists) — used by the topbar assistant bubble. */
const ICON_BRAND_COLORS = new Map<IconComponent, string>([
  [ClaudeIcon, '#D97757'],
  [OpenAIIcon, '#10A37F'],
  [GeminiIcon, '#8E75B2'],
  [KimiIcon, '#111111'],
]);

/**
 * Brand identity for a chat's assistant presence bubble. The harness wins
 * (a Claude Code / Codex chat is that product regardless of model id); a
 * vercel-harness chat is branded by its model's provider. Null means no
 * brand icon exists — callers fall back to the Sunny avatar.
 */
export function getAssistantBrand(
  model: string | null | undefined,
  harness?: string | null,
): { Icon: IconComponent; color: string } | null {
  if (harness === 'claude') return { Icon: ClaudeIcon, color: '#D97757' };
  if (harness === 'openai') return { Icon: OpenAIIcon, color: '#10A37F' };
  const id = model ?? '';
  const Icon = getProviderIcon({ provider: id.split('/')[0] ?? null, id });
  return Icon ? { Icon, color: ICON_BRAND_COLORS.get(Icon) ?? '#111111' } : null;
}
