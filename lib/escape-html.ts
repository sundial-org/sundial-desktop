/**
 * The one HTML escaper. Escapes the attribute-context characters too, so it
 * is safe for text nodes and quoted attributes alike.
 */
export function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
